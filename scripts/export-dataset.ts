/**
 * Export a Mooduel dataset release from an immutable snapshot.
 *
 * Releases are built from committed repo artifacts, never the live table,
 * so a release is reproducible from its manifest alone:
 *
 *   --source artifact (default)
 *       reads data/movie-mood-scores-v<version>.jsonl (the normalized
 *       artifact written by 11-apply-patches.mjs) + data/movie-enrichment.jsonl
 *   --source calibration-run --run <runId>
 *       (Phase 2d) reads a promoted movie_scores_calibrated run — not
 *       implemented until run promotion exists.
 *
 * Writes (refusing to clobber an existing version):
 *   dataset/mooduel-v<version>.jsonl
 *   dataset/mooduel-v<version>.csv
 *   dataset/mooduel-v<version>.manifest.json   (hashes, provenance, license)
 *
 * Parquet is generated by HuggingFace automatically on upload. Local:
 *   duckdb -c "COPY (SELECT * FROM read_json_auto('dataset/mooduel-v<version>.jsonl'))
 *             TO 'dataset/mooduel-v<version>.parquet' (FORMAT PARQUET)"
 *
 * Usage: npx tsx scripts/export-dataset.ts --version 1.0.1
 */

import { createHash } from "crypto";
import { execSync } from "child_process";
import { createReadStream, existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { createInterface } from "readline";

type Row = Record<string, unknown>;

// Published column order — v1.0 compatible. Do not reorder between patch
// releases; downstream CSV consumers index by position.
const COLUMNS = [
  "tmdb_id", "title", "year", "genres", "runtime", "tmdb_rating", "poster_path",
  "valence", "arousal", "dominance", "absorption", "hedonic", "eudaimonic", "psych_rich",
  "emotional_arc", "dominant_emotions", "mood_tags", "watch_context", "vibe_sentence",
  "pacing", "ending_type", "comfort_level", "safety_warnings", "conversation_potential",
  "rt_critic", "rt_audience", "imdb_rating",
] as const;

const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? undefined : args[i + 1];
};
const VERSION = flag("version");
const SOURCE = flag("source") ?? "artifact";
if (!VERSION || !/^\d+\.\d+\.\d+$/.test(VERSION)) {
  console.error("usage: export-dataset.ts --version X.Y.Z [--source artifact]");
  process.exit(1);
}
if (SOURCE !== "artifact") {
  console.error(`--source ${SOURCE} not implemented yet (calibration-run export lands with Phase 2d run promotion)`);
  process.exit(1);
}

const ROOT = resolve(__dirname, "..");
const SRC = resolve(ROOT, `data/movie-mood-scores-v${VERSION}.jsonl`);
const ENRICHMENT = resolve(ROOT, "data/movie-enrichment.jsonl");
const OUT_DIR = resolve(ROOT, "dataset");

function toCsvCell(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (Array.isArray(v)) return `"${JSON.stringify(v).replace(/"/g, '""')}"`;
  if (typeof v === "string") {
    const escaped = v.replace(/"/g, '""');
    return /[",\n\r]/.test(v) ? `"${escaped}"` : escaped;
  }
  return String(v);
}

const sha256 = (p: string) => createHash("sha256").update(readFileSync(p)).digest("hex");

async function main() {
  if (!existsSync(SRC)) {
    console.error(`snapshot artifact missing: ${SRC}\nRun 11-apply-patches.mjs first — releases are built from artifacts, not the live table.`);
    process.exit(1);
  }
  mkdirSync(OUT_DIR, { recursive: true });

  const outJsonl = resolve(OUT_DIR, `mooduel-v${VERSION}.jsonl`);
  const outCsv = resolve(OUT_DIR, `mooduel-v${VERSION}.csv`);
  const outManifest = resolve(OUT_DIR, `mooduel-v${VERSION}.manifest.json`);
  for (const f of [outJsonl, outCsv, outManifest]) {
    if (existsSync(f)) {
      console.error(`refusing to clobber existing release file: ${f}`);
      process.exit(1);
    }
  }

  const enrichment = new Map<number, Row>();
  for (const line of readFileSync(ENRICHMENT, "utf-8").trim().split("\n")) {
    const e = JSON.parse(line);
    enrichment.set(e.tmdbId, e);
  }

  const jsonlLines: string[] = [];
  const csvLines: string[] = [COLUMNS.join(",")];
  let rows = 0;
  let model: string | undefined;

  const rl = createInterface({ input: createReadStream(SRC) });
  for await (const line of rl) {
    const m = JSON.parse(line);
    const e = enrichment.get(m.tmdbId) ?? {};
    model ??= m.classifierModel;
    const row: Row = {
      tmdb_id: m.tmdbId,
      title: m.title,
      year: m.year,
      genres: m.genres,
      runtime: m.runtime ?? null,
      tmdb_rating: m.tmdbRating ?? null,
      poster_path: (e as Row).posterPath ?? null,
      valence: m.valence,
      arousal: m.arousal,
      dominance: m.dominance,
      absorption: m.absorptionPotential,
      hedonic: m.hedonicValence,
      eudaimonic: m.eudaimonicValence,
      psych_rich: m.psychologicallyRichValence,
      emotional_arc: m.emotionalArc,
      dominant_emotions: m.dominantEmotions,
      mood_tags: m.moodTags,
      watch_context: m.watchContext,
      vibe_sentence: m.vibeSentence,
      pacing: m.pacing,
      ending_type: m.endingType,
      comfort_level: m.comfortLevel,
      safety_warnings: m.emotionalSafetyWarnings,
      conversation_potential: m.conversationPotential,
      rt_critic: (e as Row).rtCritic ?? null,
      rt_audience: (e as Row).rtAudience ?? null,
      imdb_rating: (e as Row).imdbRating ?? null,
    };
    jsonlLines.push(JSON.stringify(row));
    csvLines.push(COLUMNS.map((c) => toCsvCell(row[c])).join(","));
    rows++;
  }

  writeFileSync(outJsonl, jsonlLines.join("\n") + "\n");
  writeFileSync(outCsv, csvLines.join("\n") + "\n");

  const gitCommit = execSync("git rev-parse HEAD", { cwd: ROOT }).toString().trim();
  const manifest = {
    name: `mooduel-v${VERSION}`,
    version: VERSION,
    created_at: new Date().toISOString(),
    rows,
    columns: COLUMNS,
    source: {
      kind: "artifact",
      files: {
        [`data/movie-mood-scores-v${VERSION}.jsonl`]: sha256(SRC),
        "data/movie-enrichment.jsonl": sha256(ENRICHMENT),
      },
      git_commit: gitCommit,
    },
    outputs: {
      [`mooduel-v${VERSION}.jsonl`]: sha256(outJsonl),
      [`mooduel-v${VERSION}.csv`]: sha256(outCsv),
    },
    provenance: {
      classifier_model: model ?? "claude-haiku-4-5-20251001",
      normalization: "score_patches ledger (see data/patches/)",
    },
    license: "CC-BY-NC-4.0",
  };
  writeFileSync(outManifest, JSON.stringify(manifest, null, 2) + "\n");

  console.log(`rows: ${rows}`);
  console.log(`wrote ${outJsonl}`);
  console.log(`wrote ${outCsv}`);
  console.log(`wrote ${outManifest}`);
  console.log("\nNext: verify locally, then upload artifacts + card together in one HF commit.");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
